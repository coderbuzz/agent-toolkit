def command_validate(args):
    errors = validate_toolkit()
    if errors:
        print("Canonical toolkit validation failed:", file=sys.stderr)
        for error in errors:
            print("- {0}".format(error), file=sys.stderr)
        return 1
    print("Canonical toolkit validation passed.")
    if args.dist:
        manifest = load_json(TOOLKIT_ROOT / "manifest.json")
        for platform in manifest["platforms"]:
            for scope, validator in (
                ("repository", validate_exported_package),
                ("global", validate_exported_global_package),
            ):
                package = args.dist.resolve() / package_relative_root(platform, scope)
                package_errors = validator(package, platform, args.bundle)
                if package_errors:
                    print("Package validation failed for {0} ({1}):".format(platform, scope), file=sys.stderr)
                    for error in package_errors:
                        print("- {0}".format(error), file=sys.stderr)
                    return 1
                print("Validated generated package: {0} ({1})".format(platform, scope))
    return 0


def command_export(args):
    errors = validate_toolkit()
    if errors:
        raise ToolkitError("Canonical validation failed:\n- " + "\n- ".join(errors))
    manifest = load_json(TOOLKIT_ROOT / "manifest.json")
    for platform in selected_platforms(args, manifest):
        for scope in ("repository", "global"):
            if args.check:
                findings = check_export_drift(platform, args.bundle, args.output, scope=scope)
                if findings:
                    print("Export drift detected for {0} ({1}):".format(platform, scope), file=sys.stderr)
                    for finding in findings:
                        print("- {0}".format(finding), file=sys.stderr)
                    return 1
                print("Export is current: {0} ({1})".format(platform, scope))
            else:
                target = atomic_export(platform, args.bundle, args.output, scope=scope)
                print("Exported {0} package to {1}".format(scope, target))
    return 0


def resolve_target(args):
    """Return the operation root, defaulting global scope to the home directory."""
    if getattr(args, "target", None) is not None:
        return args.target
    if getattr(args, "scope", "global") == "global":
        return Path(os.path.expanduser("~"))
    raise ToolkitError("--target is required for repository scope")


def _prepared_package(args):
    scope = getattr(args, "scope", "global")
    if args.package:
        package = args.package.resolve()
        metadata = load_json(package / ".agent-toolkit-package.json")
        platform = metadata.get("platform")
        bundle = metadata.get("bundle")
        package_scope = metadata.get("scope", "repository")
        if args.platform and platform != args.platform:
            raise ToolkitError("Package platform does not match --platform")
        if package_scope != scope:
            raise ToolkitError(
                "Package scope {0} does not match --scope {1}".format(package_scope, scope)
            )
        if package_scope == "repository":
            errors = validate_exported_package(package, platform, bundle)
            if errors:
                raise ToolkitError("Package validation failed:\n- " + "\n- ".join(errors))
        return None, package
    if not args.platform:
        raise ToolkitError("--platform is required when --package is omitted")
    temporary = tempfile.TemporaryDirectory(prefix="agent-toolkit-install-")
    package = Path(temporary.name) / args.platform
    if scope == "global":
        export_to_global_directory(args.platform, args.bundle, package)
    else:
        export_to_directory(args.platform, args.bundle, package)
        errors = validate_exported_package(package, args.platform, args.bundle)
        if errors:
            temporary.cleanup()
            raise ToolkitError("Generated package validation failed:\n- " + "\n- ".join(errors))
    return temporary, package


def command_install(args):
    scope = getattr(args, "scope", "global")
    target = resolve_target(args)
    temporary, package = _prepared_package(args)
    try:
        if scope == "global":
            return _run_global_install(package, target, args.apply)
        actions, conflicts, _ledger = plan_install(package, target)
        print("Install plan for {0}:".format(target.resolve()))
        print(format_actions(actions) or "No file actions.")
        if conflicts:
            print("Conflicts:", file=sys.stderr)
            for conflict in conflicts:
                print("- {0}".format(conflict), file=sys.stderr)
            return 1
        if not args.apply:
            print("Dry run only. Re-run with --apply to install.")
            return 0
        applied = apply_install(package, target)
        changed = sum(action in ("create", "update", "remove-stale") for action, _ in applied)
        print("Install completed; {0} file action(s) changed the target.".format(changed))
        return 0
    finally:
        if temporary is not None:
            temporary.cleanup()


def _run_global_install(package, target, apply):
    metadata, shared, merges, instruction_relative, exclude = global_install_parts(package)
    platform = metadata.get("platform")
    ledger_file = ledger_name("global", platform)
    file_actions, conflicts, _ledger = plan_install(
        package, target, exclude=exclude, ledger_file=ledger_file
    )
    shared_actions, shared_conflicts = plan_shared_skills(package, target, platform, shared)
    instruction_preview = []
    if instruction_relative:
        planned, instruction_conflicts = plan_instruction_block(package, target, instruction_relative)
        conflicts.extend(instruction_conflicts)
        if planned is not None:
            instruction_preview.append((planned[0], planned[1]))
    conflicts.extend(shared_conflicts)

    print("Global install plan for {0} into {1}:".format(platform, target.resolve()))
    print(format_actions(file_actions + shared_actions + instruction_preview) or "No file actions.")
    if conflicts:
        print("Conflicts:", file=sys.stderr)
        for conflict in conflicts:
            print("- {0}".format(conflict), file=sys.stderr)
        return 1
    if not apply:
        print("Dry run only. Re-run with --apply to install.")
        return 0
    apply_install(package, target, exclude=exclude, ledger_file=ledger_file)
    apply_shared_skills(package, target, platform, shared)
    if instruction_relative:
        apply_instruction_block(package, target, instruction_relative)
    print("Global install completed for {0}.".format(platform))
    return 0


def command_uninstall(args):
    scope = getattr(args, "scope", "global")
    target = resolve_target(args)
    if scope == "global":
        return _run_global_uninstall(target, args.platform, args.apply)
    actions, warnings = plan_uninstall(target)
    print("Uninstall plan for {0}:".format(target.resolve()))
    print(format_actions(actions) or "No managed files found.")
    for warning in warnings:
        print("Warning: {0}".format(warning), file=sys.stderr)
    if not args.apply:
        print("Dry run only. Re-run with --apply to uninstall.")
        return 0
    applied, final_warnings = apply_uninstall(target)
    removed = sum(action == "remove" for action, _ in applied)
    print("Uninstall completed; removed {0} unchanged managed file(s).".format(removed))
    return 0 if not final_warnings else 2


def _run_global_uninstall(target, platform, apply):
    if not platform:
        raise ToolkitError("--platform is required for global uninstall")
    ledger_file = ledger_name("global", platform)
    file_actions, warnings = plan_uninstall(target, ledger_file)
    shared_actions, shared_warnings = plan_shared_skills_uninstall(target, platform)
    warnings = warnings + shared_warnings
    adapter = load_json(TOOLKIT_ROOT / "platforms" / platform / "adapter.json")
    global_block = adapter.get("global", {})
    merge_actions = []
    instruction_relative = global_block.get("instruction_path")
    instruction_action = None
    if instruction_relative:
        instruction_action = plan_instruction_unblock(target, instruction_relative)
        if instruction_action[0] != "instruction-unblock-absent":
            merge_actions.append(instruction_action)

    print("Global uninstall plan for {0} from {1}:".format(platform, target.resolve()))
    print(format_actions(file_actions + shared_actions + merge_actions) or "No managed files found.")
    for warning in warnings:
        print("Warning: {0}".format(warning), file=sys.stderr)
    if not apply:
        print("Dry run only. Re-run with --apply to uninstall.")
        return 0
    apply_uninstall(target, ledger_file)
    apply_shared_skills_uninstall(target, platform)
    if instruction_relative:
        apply_instruction_unblock(target, instruction_relative)
    print("Global uninstall completed for {0}.".format(platform))
    return 0 if not warnings else 2


def command_check_drift(args):
    manifest = load_json(TOOLKIT_ROOT / "manifest.json")
    failed = False
    for platform in selected_platforms(args, manifest):
        for scope in ("repository", "global"):
            findings = check_export_drift(platform, args.bundle, args.output, scope=scope)
            if findings:
                failed = True
                print("Drift detected for {0} ({1}):".format(platform, scope), file=sys.stderr)
                for finding in findings:
                    print("- {0}".format(finding), file=sys.stderr)
            else:
                print("No drift: {0} ({1})".format(platform, scope))
    return 1 if failed else 0


def add_platform_selector(parser):
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--platform", choices=sorted(VALID_PLATFORMS))
    group.add_argument("--all", action="store_true", help="Process every supported platform.")


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    validate_parser = subparsers.add_parser("validate", help="Validate canonical or generated content.")
    validate_parser.add_argument("--dist", type=Path, help="Also validate all packages under this directory.")
    validate_parser.add_argument("--bundle", default="core", choices=("core", "full", "quality"))
    validate_parser.set_defaults(handler=command_validate)

    export_parser = subparsers.add_parser("export", help="Generate platform-native packages.")
    add_platform_selector(export_parser)
    export_parser.add_argument("--bundle", default="core", choices=("core", "full", "quality"))
    export_parser.add_argument("--output", type=Path, default=TOOLKIT_ROOT / "dist")
    export_parser.add_argument("--check", action="store_true", help="Check output without changing it.")
    export_parser.set_defaults(handler=command_export)

    install_parser = subparsers.add_parser("install", help="Preview or install a platform package.")
    install_parser.add_argument("--platform", choices=sorted(VALID_PLATFORMS))
    install_parser.add_argument("--package", type=Path, help="Use an existing generated package.")
    install_parser.add_argument("--bundle", default="core", choices=("core", "full", "quality"))
    install_parser.add_argument("--scope", default="global", choices=("repository", "global"))
    install_parser.add_argument(
        "--target",
        type=Path,
        default=None,
        help="Install root. Required for repository scope; defaults to the home directory for global scope.",
    )
    install_parser.add_argument("--apply", action="store_true", help="Apply the previewed safe changes.")
    install_parser.set_defaults(handler=command_install)

    uninstall_parser = subparsers.add_parser("uninstall", help="Preview or remove unchanged managed files.")
    uninstall_parser.add_argument("--platform", choices=sorted(VALID_PLATFORMS))
    uninstall_parser.add_argument("--scope", default="global", choices=("repository", "global"))
    uninstall_parser.add_argument(
        "--target",
        type=Path,
        default=None,
        help="Uninstall root. Optional; defaults to the home directory for global scope, required for repository scope.",
    )
    uninstall_parser.add_argument("--apply", action="store_true", help="Apply the previewed safe removals.")
    uninstall_parser.set_defaults(handler=command_uninstall)

    drift_parser = subparsers.add_parser("check-drift", help="Compare generated output with canonical sources.")
    add_platform_selector(drift_parser)
    drift_parser.add_argument("--bundle", default="core", choices=("core", "full", "quality"))
    drift_parser.add_argument("--output", type=Path, default=TOOLKIT_ROOT / "dist")
    drift_parser.set_defaults(handler=command_check_drift)
    return parser


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return args.handler(args)
    except ToolkitError as exc:
        print("Error: {0}".format(exc), file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("Interrupted.", file=sys.stderr)
        return 130


if __name__ == "__main__":
    sys.exit(main())
