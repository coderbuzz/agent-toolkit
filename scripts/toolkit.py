class ToolkitError(Exception):
    """A user-actionable toolkit error."""


def _reject_duplicate_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ToolkitError("Duplicate JSON key: {0}".format(key))
        result[key] = value
    return result


def _reject_constant(value):
    raise ToolkitError("Non-finite JSON value is not allowed: {0}".format(value))


def load_json(path):
    """Load JSON while rejecting duplicate keys and non-finite numbers."""
    try:
        return json.loads(
            path.read_text(encoding="utf-8"),
            object_pairs_hook=_reject_duplicate_keys,
            parse_constant=_reject_constant,
        )
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ToolkitError("Cannot read valid JSON from {0}: {1}".format(path, exc))


def safe_relative_path(value):
    """Return a normalized relative path or reject an unsafe value."""
    if not isinstance(value, str) or not value or "\x00" in value or "\\" in value:
        raise ToolkitError("Unsafe relative path: {0!r}".format(value))
    path = PurePosixPath(value)
    if path.is_absolute() or any(part in ("", ".", "..") for part in path.parts):
        raise ToolkitError("Unsafe relative path: {0!r}".format(value))
    if re.match(r"^[A-Za-z]:", value):
        raise ToolkitError("Unsafe relative path: {0!r}".format(value))
    return path


def ensure_within(root, relative):
    """Resolve a child path and ensure it remains under root."""
    rel = safe_relative_path(str(relative))
    root_resolved = root.resolve()
    candidate = (root / Path(*rel.parts)).resolve()
    try:
        candidate.relative_to(root_resolved)
    except ValueError:
        raise ToolkitError("Path escapes target root: {0}".format(relative))
    return candidate


def safe_operation_root(path, label):
    resolved = path.resolve()
    if resolved == Path(resolved.anchor):
        raise ToolkitError("Refusing to use the filesystem root as {0}".format(label))
    return resolved


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def file_sha256(path):
    return sha256_bytes(path.read_bytes())


def source_files(root=TOOLKIT_ROOT):
    """Return canonical source inputs in deterministic order."""
    files = []
    for relative in SOURCE_FILES:
        path = root / relative
        if path.is_file():
            files.append(path)
    for relative in SOURCE_DIRS:
        directory = root / relative
        if directory.is_dir():
            files.extend(path for path in directory.rglob("*") if path.is_file())
    return sorted(files, key=lambda item: item.relative_to(root).as_posix())


def source_digest(root=TOOLKIT_ROOT):
    digest = hashlib.sha256()
    for path in source_files(root):
        relative = path.relative_to(root).as_posix().encode("utf-8")
        digest.update(relative)
        digest.update(b"\x00")
        digest.update(path.read_bytes())
        digest.update(b"\x00")
    return digest.hexdigest()


def all_skill_names(manifest):
    names = []
    for group in ("lifecycle", "cross_cutting", "optional"):
        names.extend(manifest["skills"].get(group, []))
    return names


def bundle_skill_names(manifest, bundle):
    if bundle not in manifest.get("bundles", {}):
        raise ToolkitError("Unknown bundle: {0}".format(bundle))
    result = []
    for entry in manifest["bundles"][bundle]:
        if entry in manifest.get("skills", {}):
            result.extend(manifest["skills"][entry])
        else:
            result.append(entry)
    seen = set()
    ordered = []
    for name in result:
        if name not in seen:
            seen.add(name)
            ordered.append(name)
    return ordered


def generated_marker(version, digest, prefix="<!--", suffix="-->"):
    return "{0} {1} {2}; source-sha256: {3}; do not edit. {4}\n".format(
        prefix, GENERATED_TEXT, version, digest, suffix
    )


def parse_frontmatter(path):
    """Parse the small YAML subset used by canonical SKILL.md files."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != "---":
        raise ToolkitError("Missing YAML frontmatter in {0}".format(path))
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise ToolkitError("Unclosed YAML frontmatter in {0}".format(path))
    values = {}
    current = None
    for line in lines[1:end]:
        if line.startswith((" ", "\t")):
            if current is None:
                raise ToolkitError("Invalid frontmatter indentation in {0}".format(path))
            values[current] = (values[current] + " " + line.strip()).strip()
            continue
        if ":" not in line:
            raise ToolkitError("Invalid frontmatter line in {0}: {1}".format(path, line))
        key, value = line.split(":", 1)
        key = key.strip()
        if key in values:
            raise ToolkitError("Duplicate frontmatter key in {0}: {1}".format(path, key))
        current = key
        values[key] = value.strip().lstrip(">|-").strip()
    return values


def _unique_strings(values, label, errors):
    if not isinstance(values, list) or not all(isinstance(item, str) for item in values):
        errors.append("{0} must be a list of strings".format(label))
        return []
    duplicates = sorted({item for item in values if values.count(item) > 1})
    if duplicates:
        errors.append("{0} contains duplicates: {1}".format(label, ", ".join(duplicates)))
    folded = {}
    for item in values:
        folded.setdefault(item.casefold(), []).append(item)
    collisions = [items for items in folded.values() if len(items) > 1]
    if collisions:
        errors.append("{0} contains case-insensitive collisions: {1}".format(label, collisions))
    return values


def validate_manifest(manifest, errors):
    required = {
        "schema_version",
        "name",
        "version",
        "canonical",
        "platforms",
        "skills",
        "bundles",
        "install_policy",
    }
    missing = required - set(manifest)
    if missing:
        errors.append("Manifest missing keys: {0}".format(", ".join(sorted(missing))))
        return
    if manifest["schema_version"] != 1:
        errors.append("Unsupported manifest schema_version")
    if not re.match(r"^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$", manifest["version"]):
        errors.append("Manifest version is not semantic versioning: {0}".format(manifest["version"]))
    platforms = _unique_strings(manifest["platforms"], "manifest.platforms", errors)
    unknown = set(platforms) - VALID_PLATFORMS
    if unknown:
        errors.append("Unknown platforms: {0}".format(", ".join(sorted(unknown))))
    for group in ("lifecycle", "cross_cutting", "optional"):
        _unique_strings(manifest["skills"].get(group), "manifest.skills.{0}".format(group), errors)
    _unique_strings(all_skill_names(manifest), "all manifest skills", errors)
    known_skills = set(all_skill_names(manifest))
    for bundle, entries in manifest["bundles"].items():
        _unique_strings(entries, "manifest.bundles.{0}".format(bundle), errors)
        for entry in entries:
            if entry not in manifest["skills"] and entry not in known_skills:
                errors.append("Bundle {0} references unknown skill/group: {1}".format(bundle, entry))
    for key, value in manifest["canonical"].items():
        try:
            safe_relative_path(value)
        except ToolkitError as exc:
            errors.append("manifest.canonical.{0}: {1}".format(key, exc))
    policy = manifest["install_policy"]
    if policy.get("overwrite") != "never" or policy.get("preview_required") is not True:
        errors.append("Install policy must require preview and never overwrite by default")


def validate_skills(manifest, errors, root=TOOLKIT_ROOT):
    skill_root = root / manifest["canonical"]["skills"]
    expected = set(all_skill_names(manifest))
    actual = {path.name for path in skill_root.iterdir() if path.is_dir()} if skill_root.is_dir() else set()
    if expected != actual:
        errors.append(
            "Skill directory mismatch; missing={0}, extra={1}".format(
                sorted(expected - actual), sorted(actual - expected)
            )
        )
    for name in sorted(expected & actual):
        skill_file = skill_root / name / "SKILL.md"
        if not skill_file.is_file():
            errors.append("Missing SKILL.md for {0}".format(name))
            continue
        try:
            metadata = parse_frontmatter(skill_file)
        except ToolkitError as exc:
            errors.append(str(exc))
            continue
        if set(metadata) - {"name", "description", "invocation", "role", "supersedes"}:
            errors.append("{0} frontmatter must contain only name, description, invocation, role, and supersedes".format(name))
        if metadata.get("name") != name:
            errors.append("Skill folder/name mismatch: {0}".format(name))
        description = metadata.get("description", "")
        if not description or len(description) > 1024:
            errors.append("Skill {0} needs a concise non-empty description".format(name))
        text = skill_file.read_text(encoding="utf-8")
        for token in FORBIDDEN_SKILL_TEXT:
            if token.casefold() in text.casefold():
                errors.append("Skill {0} contains non-portable text: {1}".format(name, token))
        if re.search(r"\b(?:TODO|TBD|FIXME)\b", text, re.IGNORECASE):
            errors.append("Skill {0} contains placeholder text".format(name))
        long_lines = [index for index, line in enumerate(text.splitlines(), 1) if len(line) > 120]
        if long_lines:
            errors.append("Skill {0} has lines over 120 characters: {1}".format(name, long_lines))
        metadata_file = skill_root / name / "agents" / "openai.yaml"
        if not metadata_file.is_file():
            errors.append("Skill {0} is missing agents/openai.yaml".format(name))
        for match in re.finditer(r"\[[^\]]+\]\(([^)]+)\)", text):
            reference = match.group(1).split("#", 1)[0]
            if not reference or "://" in reference or reference.startswith("#"):
                continue
            try:
                referenced = ensure_within(skill_file.parent, reference)
            except ToolkitError as exc:
                errors.append("Skill {0} has unsafe reference: {1}".format(name, exc))
                continue
            if not referenced.exists():
                errors.append("Skill {0} has broken reference: {1}".format(name, reference))



def validate_adapters(manifest, errors, root=TOOLKIT_ROOT):
    for platform in manifest["platforms"]:
        path = root / "platforms" / platform / "adapter.json"
        if not path.is_file():
            errors.append("Missing adapter descriptor for {0}".format(platform))
            continue
        adapter = load_json(path)
        if adapter.get("id") != platform:
            errors.append("Adapter ID mismatch for {0}".format(platform))
        try:
            safe_relative_path(adapter["skill_path"].replace("{name}", "skill"))
        except (KeyError, ToolkitError) as exc:
            errors.append("Unsafe or missing adapter path for {0}: {1}".format(platform, exc))
        global_block = adapter.get("global")
        if global_block is None:
            errors.append("Adapter {0} is missing a global scope block".format(platform))
        else:
            try:
                safe_relative_path(global_block["instruction_path"])
                safe_relative_path(global_block["skill_path"].replace("{name}", "skill"))
            except (KeyError, ToolkitError) as exc:
                errors.append("Unsafe or missing global path for {0}: {1}".format(platform, exc))
            command_pattern = global_block.get("command_path")
            if command_pattern:
                try:
                    safe_relative_path(command_pattern.replace("{name}", "skill"))
                except ToolkitError as exc:
                    errors.append("Unsafe global command path for {0}: {1}".format(platform, exc))


def validate_toolkit(root=TOOLKIT_ROOT):
    errors = []
    manifest = load_json(root / "manifest.json")
    validate_manifest(manifest, errors)
    if errors:
        return errors
    validate_skills(manifest, errors, root)
    validate_adapters(manifest, errors, root)
    for relative in SOURCE_DIRS:
        path = root / relative
        if path.is_symlink():
            errors.append("Canonical source directory must not be a symlink: {0}".format(path))
    for path in source_files(root):
        if path.is_symlink():
            errors.append("Canonical export input must not be a symlink: {0}".format(path))
    return errors


def yaml_value(value):
    """Render a scalar as a YAML-compatible JSON string."""
    return json.dumps(value, ensure_ascii=False)















def render_opencode_command(skill_root, name):
    """Render an OpenCode slash command that loads one skill."""
    frontmatter = parse_frontmatter(skill_root / "SKILL.md")
    description = frontmatter.get("description", "Run the {0} agent-toolkit skill".format(name))
    body = (
        "Load and run the `{0}` skill and follow its procedure for this task. "
        "Keep the skill's stop conditions and outputs as the source of truth."
    ).format(name)
    return (
        "---\ndescription: {0}\n---\n\n{1}\n".format(yaml_value(description), body)
    )


def write_text(root, relative, content):
    destination = ensure_within(root, relative)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)


def copy_file(source, destination_root, relative):
    if source.is_symlink():
        raise ToolkitError("Symlinked source files are not exportable: {0}".format(source))
    destination = ensure_within(destination_root, relative)
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(str(source), str(destination))


def copy_tree(source, destination_root, relative_root):
    if source.is_symlink():
        raise ToolkitError("Symlinked source directories are not exportable: {0}".format(source))
    for path in sorted(source.rglob("*")):
        if path.is_symlink():
            raise ToolkitError("Symlinked source paths are not exportable: {0}".format(path))
        if path.is_file():
            relative = PurePosixPath(relative_root) / PurePosixPath(path.relative_to(source).as_posix())
            copy_file(path, destination_root, relative.as_posix())


def export_to_directory(platform, bundle, destination, root=TOOLKIT_ROOT):
    """Create one target-ready platform package in a new directory."""
    manifest = load_json(root / "manifest.json")
    if platform not in manifest["platforms"]:
        raise ToolkitError("Unsupported platform: {0}".format(platform))
    selected_skills = bundle_skill_names(manifest, bundle)
    digest = source_digest(root)
    version = manifest["version"]
    destination.mkdir(parents=True, exist_ok=False)

    copy_file(root / "AGENTS.md", destination, "AGENTS.md")
    for source_name, target_name in (
        ("instructions", ".agents/instructions"),
        ("standards", ".agents/standards"),
        ("templates", ".agents/templates"),
    ):
        copy_tree(root / source_name, destination, target_name)

    adapter = load_json(root / "platforms" / platform / "adapter.json")
    for skill_name in selected_skills:
        source = root / manifest["canonical"]["skills"] / skill_name
        target_pattern = adapter["skill_path"].replace("{name}", skill_name)
        copy_tree(source, destination, target_pattern)

    if platform == "github-copilot":
        instructions = generated_marker(version, digest) + (root / "AGENTS.md").read_text(encoding="utf-8")
        write_text(destination, adapter["instruction_path"], instructions)
    elif platform == "claude-code":
        content = generated_marker(version, digest) + "@AGENTS.md\n"
        write_text(destination, adapter["instruction_path"], content)
    elif platform == "omp":
        content = generated_marker(version, digest) + (root / "AGENTS.md").read_text(encoding="utf-8")
        write_text(destination, ".omp/AGENTS.md", content)

    metadata = {
        "schema_version": 1,
        "toolkit": manifest["name"],
        "version": version,
        "source_sha256": digest,
        "platform": platform,
        "bundle": bundle,
        "skills": selected_skills,
    }
    write_text(
        destination,
        ".agent-toolkit-package.json",
        json.dumps(metadata, indent=2, sort_keys=True) + "\n",
    )
    return metadata


def export_to_global_directory(platform, bundle, destination, root=TOOLKIT_ROOT):
    """Create one home-relative platform package for global installation.

    Skills are laid out at the shared ``.agents/skills`` location so a single
    installed copy serves every platform. Agents and instructions use the
    platform's global home-relative paths.
    """
    manifest = load_json(root / "manifest.json")
    if platform not in manifest["platforms"]:
        raise ToolkitError("Unsupported platform: {0}".format(platform))
    adapter = load_json(root / "platforms" / platform / "adapter.json")
    global_block = adapter.get("global")
    if not global_block:
        raise ToolkitError("Platform {0} has no global scope block".format(platform))

    selected_skills = bundle_skill_names(manifest, bundle)
    digest = source_digest(root)
    version = manifest["version"]
    destination.mkdir(parents=True, exist_ok=False)

    shared_skill_files = []
    for skill_name in selected_skills:
        source = root / manifest["canonical"]["skills"] / skill_name
        target_pattern = global_block["skill_path"].replace("{name}", skill_name)
        copy_tree(source, destination, target_pattern)
        for path in sorted(source.rglob("*")):
            if path.is_file():
                relative = (
                    PurePosixPath(target_pattern)
                    / PurePosixPath(path.relative_to(source).as_posix())
                )
                shared_skill_files.append(relative.as_posix())

    merge_files = []
    instruction_relative = global_block["instruction_path"]
    instruction_content = generated_marker(version, digest) + (
        root / "AGENTS.md"
    ).read_text(encoding="utf-8")
    write_text(destination, instruction_relative, instruction_content)

    command_path_pattern = global_block.get("command_path")
    if command_path_pattern:
        for skill_name in selected_skills:
            command_relative = command_path_pattern.replace("{name}", skill_name)
            command = render_opencode_command(root / manifest["canonical"]["skills"] / skill_name, skill_name)
            write_text(destination, command_relative, command)

    metadata = {
        "schema_version": 1,
        "toolkit": manifest["name"],
        "version": version,
        "source_sha256": digest,
        "platform": platform,
        "bundle": bundle,
        "scope": "global",
        "skills": selected_skills,
        "shared_skill_files": sorted(shared_skill_files),
        "merge_files": merge_files,
        "instruction_path": instruction_relative,
    }
    write_text(
        destination,
        ".agent-toolkit-package.json",
        json.dumps(metadata, indent=2, sort_keys=True) + "\n",
    )
    return metadata


def package_files(root, include_metadata=True):
    files = {}
    if not root.is_dir():
        return files
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ToolkitError("Package contains a symlink: {0}".format(path))
        if path.is_file():
            relative = path.relative_to(root).as_posix()
            safe_relative_path(relative)
            if not include_metadata and relative == ".agent-toolkit-package.json":
                continue
            folded = relative.casefold()
            if any(existing.casefold() == folded and existing != relative for existing in files):
                raise ToolkitError("Case-insensitive package path collision: {0}".format(relative))
            files[relative] = file_sha256(path)
    return files


def validate_exported_package(package_root, platform, bundle, root=TOOLKIT_ROOT):
    errors = []
    if package_root.is_symlink() or not package_root.is_dir():
        return ["Package root must be a regular directory: {0}".format(package_root)]
    metadata_path = package_root / ".agent-toolkit-package.json"
    if metadata_path.is_symlink() or not metadata_path.is_file():
        return ["Package metadata must be a regular file: {0}".format(metadata_path)]
    try:
        metadata = load_json(metadata_path)
    except ToolkitError as exc:
        return [str(exc)]
    manifest = load_json(root / "manifest.json")
    if platform not in manifest["platforms"]:
        return ["Unsupported package platform: {0}".format(platform)]
    if bundle not in manifest["bundles"]:
        return ["Unsupported package bundle: {0}".format(bundle)]
    expected_metadata = {
        "toolkit": manifest["name"],
        "version": manifest["version"],
        "source_sha256": source_digest(root),
        "platform": platform,
        "bundle": bundle,
    }
    for key, expected in expected_metadata.items():
        if metadata.get(key) != expected:
            errors.append("Package metadata mismatch for {0}".format(key))
    expected_skills = set(bundle_skill_names(manifest, bundle))
    if set(metadata.get("skills", [])) != expected_skills:
        errors.append("Package skill list does not match bundle {0}".format(bundle))
    try:
        files = package_files(package_root)
    except ToolkitError as exc:
        return errors + [str(exc)]
    if "AGENTS.md" not in files:
        errors.append("Package is missing AGENTS.md")
    adapter = load_json(root / "platforms" / platform / "adapter.json")
    for skill in expected_skills:
        skill_file = adapter["skill_path"].replace("{name}", skill) + "/SKILL.md"
        if skill_file not in files:
            errors.append("Package is missing skill: {0}".format(skill))
    if platform == "github-copilot" and adapter["instruction_path"] not in files:
        errors.append("Package is missing GitHub Copilot instructions")
    if platform == "claude-code":
        instruction_path = adapter["instruction_path"]
        if instruction_path not in files or "@AGENTS.md" not in (package_root / instruction_path).read_text(encoding="utf-8"):
            errors.append("Package is missing the Claude AGENTS.md import")
    return errors


def validate_exported_global_package(package_root, platform, bundle, root=TOOLKIT_ROOT):
    errors = []
    if package_root.is_symlink() or not package_root.is_dir():
        return ["Package root must be a regular directory: {0}".format(package_root)]
    metadata_path = package_root / ".agent-toolkit-package.json"
    if metadata_path.is_symlink() or not metadata_path.is_file():
        return ["Package metadata must be a regular file: {0}".format(metadata_path)]
    try:
        metadata = load_json(metadata_path)
    except ToolkitError as exc:
        return [str(exc)]
    manifest = load_json(root / "manifest.json")
    if platform not in manifest["platforms"]:
        return ["Unsupported package platform: {0}".format(platform)]
    if bundle not in manifest["bundles"]:
        return ["Unsupported package bundle: {0}".format(bundle)]
    expected_metadata = {
        "toolkit": manifest["name"],
        "version": manifest["version"],
        "source_sha256": source_digest(root),
        "platform": platform,
        "bundle": bundle,
        "scope": "global",
    }
    for key, expected in expected_metadata.items():
        if metadata.get(key) != expected:
            errors.append("Package metadata mismatch for {0}".format(key))
    expected_skills = set(bundle_skill_names(manifest, bundle))
    if set(metadata.get("skills", [])) != expected_skills:
        errors.append("Package skill list does not match bundle {0}".format(bundle))
    try:
        files = package_files(package_root)
    except ToolkitError as exc:
        return errors + [str(exc)]
    for relative in metadata.get("shared_skill_files", []):
        if relative not in files:
            errors.append("Package is missing shared skill file: {0}".format(relative))
    adapter = load_json(root / "platforms" / platform / "adapter.json")
    global_block = adapter.get("global", {})
    instruction_relative = metadata.get("instruction_path")
    if instruction_relative:
        if instruction_relative not in files:
            errors.append("Package is missing global instruction file")
        elif GENERATED_TEXT not in (package_root / instruction_relative).read_text(encoding="utf-8"):
            errors.append("Generated marker missing from global instruction file")
    else:
        errors.append("Package metadata is missing instruction_path")
    for entry in metadata.get("merge_files", []):
        if entry.get("merge_file") not in files:
            errors.append("Package is missing merge file: {0}".format(entry.get("merge_file")))
